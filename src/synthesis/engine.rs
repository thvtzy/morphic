// ── Global synthesis statistics ──────────────────────────

static CANDIDATE_COUNT: AtomicU64 = AtomicU64::new(0);
static ELAPSED_MS: AtomicU64 = AtomicU64::new(0);

pub fn candidate_count() -> u64 { CANDIDATE_COUNT.load(Ordering::Relaxed) }
