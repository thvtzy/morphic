pub const SPDX_LINE: &str = "// SPDX-License-Identifier: MIT";
pub const PRAGMA_LINE: &str = "pragma solidity ^0.8.24;";

const PROOF_BOUNDARY_HEADER: &str = r#"/// @notice Generated by Morphic (`--target solidity`, IKONIK_18_SCOPE).
/// @dev Proof boundary (D8a):
///   - Z3 verifies Morphic IR over unbounded integers (Z) with totalized div/mod
///     under the specification's `require:` preconditions.
///   - Solidity ^0.8.24 enforces `require:` at runtime and reverts on 256-bit
///     overflow/underflow (Panic(0x11)) or division/modulo by zero (Panic(0x12)).
///   - Negative integer division diverges between Z3 (Euclidean) and EVM
///     (truncating toward zero); semantics are identical on non-negative domains
///     (a >= 0, b > 0).
///   - String length uses `bytes(s).length` (UTF-8 bytes; exact for ASCII and emptiness).
"#;

/// Generate a complete, self-contained Solidity `^0.8.24` contract
/// for a single Morphic candidate implementation.
pub fn generate_solidity(candidate: &CandidateImplementation) -> Result<String, CodegenError> {
    let mut needed_append: BTreeSet<&'static str> = BTreeSet::new();
    let mut needed_clone: BTreeSet<&'static str> = BTreeSet::new();

    // Collect transitive prelude helpers used by body AND preconditions.
    let helper_names = collect_transitive_helpers(candidate);
    let mut allowed_callees: BTreeSet<String> = helper_names.clone();
    allowed_callees.insert(candidate.spec.name.clone());

    let main_fn = render_solidity_function(
        candidate,
        "public",
        None,
        &allowed_callees,
        &mut needed_append,
        &mut needed_clone,
    )?;

    let mut helper_fns: Vec<String> = Vec::new();
    if !helper_names.is_empty() {
        let specs = crate::stdlib::prelude_specs();
        for name in &helper_names {
            let spec = specs
                .iter()
                .find(|s| &s.name == name)
                .ok_or_else(|| {
                    CodegenError::InternalError(format!(
                        "target \"solidity\": prelude helper `{name}` has no spec"
                    ))
                })?
                .clone();
            let body = crate::stdlib::shipped_body(name).ok_or_else(|| {
                CodegenError::InternalError(format!(
                    "target \"solidity\": prelude helper `{name}` has no shipped body"
                ))
            })?;
            let helper = CandidateImplementation {
                id: 0,
                body,
                spec_name: name.clone(),
                spec,
                score: 0.0,
                scores: ScoreBreakdown {
                    test_pass_ratio: 0.0,
                    constraint_score: 0.0,
                    complexity_score: 0.0,
                    quality_score: 0.0,
                    synthesis_time_us: 0,
                },
                generation: 0,
                provenance: Provenance::HumanGuided,
                verified: true,
                verification_status: None,
            };
            helper_fns.push(render_solidity_function(
                &helper,
                "internal",
                None,
                &allowed_callees,
                &mut needed_append,
                &mut needed_clone,
            )?);
        }
    }

    let cname = contract_name(&candidate.spec.name);
    let mut out = String::new();
    out.push_str(SPDX_LINE);
    out.push('\n');
    out.push_str(PRAGMA_LINE);
    out.push_str("\n\n");
    out.push_str(PROOF_BOUNDARY_HEADER);
    out.push_str(&format!("contract {cname} {{\n"));
    out.push_str(&main_fn);

    for h in &helper_fns {
        out.push('\n');
        out.push_str(h);
    }

    for elem_ty in &needed_append {
        out.push('\n');
        out.push_str(&render_append_helper(elem_ty));
    }
    for elem_ty in &needed_clone {
        out.push('\n');
        out.push_str(&render_clone_helper(elem_ty));
    }

    out.push_str("}\n");
    Ok(out)
}

/// Collect all transitively referenced prelude/installed entries from
/// a candidate's body and preconditions, excluding the candidate's own name.
pub(crate) fn collect_transitive_helpers(candidate: &CandidateImplementation) -> BTreeSet<String> {
    let entry_names = library_entry_names();
    let mut used: BTreeSet<String> = BTreeSet::new();
    let mut direct = LibraryUse::default();
    scan_library_use(&candidate.body, &entry_names, &mut direct);
    let mut queue: Vec<String> = direct.entries.into_iter().collect();
    let mut from_pre: BTreeSet<String> = BTreeSet::new();
    for pre in &candidate.spec.preconditions {
        scan_constraint_library_use(pre, &entry_names, &mut from_pre);
    }
    queue.extend(from_pre);

    let all_specs = crate::stdlib::prelude_specs();
    while let Some(name) = queue.pop() {
        if used.insert(name.clone()) {
            if let Some(body) = crate::stdlib::shipped_body(&name) {
                let mut inner = LibraryUse::default();
                scan_library_use(&body, &entry_names, &mut inner);
                queue.extend(inner.entries);
            }
            if let Some(spec) = all_specs.iter().find(|s| s.name == name) {
                let mut inner = BTreeSet::new();
                for pre in &spec.preconditions {
                    scan_constraint_library_use(pre, &entry_names, &mut inner);
                }
                queue.extend(inner);
            }
        }
    }
    used.remove(&candidate.spec.name);
    used
}

// ── Value Kinds & Type Mapping ────────────────────────────

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum SolValTy {
    Scalar(&'static str),
    Bool,
    Str,
    List(&'static str),
    Unit,
}

fn scalar_sol_name(ty: &TypeRef) -> Option<&'static str> {
    match ty {
        TypeRef::Int => Some("int256"),
        TypeRef::Bool => Some("bool"),
        TypeRef::I8 => Some("int8"),
        TypeRef::I16 => Some("int16"),
        TypeRef::I32 => Some("int32"),
        TypeRef::I64 => Some("int64"),
        TypeRef::U8 => Some("uint8"),
        TypeRef::U16 => Some("uint16"),
        TypeRef::U32 => Some("uint32"),
        TypeRef::U64 => Some("uint64"),
        _ => None,
    }
}

fn sol_val_ty(ty: &TypeRef, allow_unit: bool) -> Result<SolValTy, CodegenError> {
    match ty {
        TypeRef::Bool => Ok(SolValTy::Bool),
        TypeRef::Int
        | TypeRef::I8
        | TypeRef::I16
        | TypeRef::I32
        | TypeRef::I64
        | TypeRef::U8
        | TypeRef::U16
        | TypeRef::U32
        | TypeRef::U64 => Ok(SolValTy::Scalar(scalar_sol_name(ty).unwrap())),
        TypeRef::String => Ok(SolValTy::Str),
        TypeRef::List(inner) => match scalar_sol_name(inner) {
            Some(elem) => Ok(SolValTy::List(elem)),
            None => Err(CodegenError::InvalidIR(format!(
                "target \"solidity\" does not support list element type `{inner}` in `{ty}` \
                 (only scalar lists are in the direct-ABI subset)"
            ))),
        },
        TypeRef::Unit if allow_unit => Ok(SolValTy::Unit),
        other => Err(CodegenError::InvalidIR(format!(
            "target \"solidity\" does not support type `{other}` \
             (direct-ABI subset only; IKONIK_18_SCOPE §3.1)"
        ))),
    }
}

fn sol_type_decl(val_ty: SolValTy) -> String {
    match val_ty {
        SolValTy::Scalar(s) => s.to_string(),
        SolValTy::Bool => "bool".to_string(),
        SolValTy::Str => "string memory".to_string(),
        SolValTy::List(elem) => format!("{elem}[] memory"),
        SolValTy::Unit => String::new(),
    }
}

// ── Identifier & Keyword Sanitization ─────────────────────

pub(crate) fn sol_ident(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 1);
    for (i, ch) in name.chars().enumerate() {
        if ch == '_' || ch.is_ascii_alphanumeric() {
            if i == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        return "_ident".to_string();
    }
    if is_sol_keyword(&out) {
        out.push('_');
    }
    out
}

pub(crate) fn contract_name(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(|c: char| !c.is_ascii_alphanumeric()) {
        if part.is_empty() {
            continue;
        }
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(chars);
        }
    }
    if out.is_empty() || out.chars().next().unwrap().is_ascii_digit() || is_sol_keyword(&out) {
        format!("Morphic{out}")
    } else {
        out
    }
}

