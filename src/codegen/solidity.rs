// ─────────────────────────────────────────────────────────────
//  SOLIDITY CODEGEN (Phase 168, 1.8 Smart-Contract Target —
//  IKONIK_18_SCOPE.md §3–§5, decisions D1a–D9a)
//
//  Emits self-contained Solidity `^0.8.24` pure contracts from
//  Morphic IR candidates:
//
//    * Direct-ABI types only (D1a/D3a):
//        Int -> int256, Bool -> bool, I8..I64 -> int8..int64,
//        U8..U64 -> uint8..uint64, String -> string memory,
//        List<scalar> -> <scalar>[] memory, Unit (return only).
//      Unsupported types (Float, Char, Option, Result, Function,
//      Map, Set, Stream, Tuple, Array, Generic, Ref, Named,
//      nested/String lists) refuse by name with CodegenError.
//    * Always-on runtime `require(<cond>, "...");` guards for
//      every `spec.preconditions` row (D2a). Quantified rows
//      (`Forall`/`Exists`) and unrenderable expressions REFUSE
//      by name — never emitting `require(true)`.
//    * Stateless `public pure` entrypoints + deduplicated
//      transitive prelude helpers as `internal pure` (D4a),
//      emitting memory-array helpers (`_morphic_append_*`,
//      `_morphic_clone_*`) only when referenced so scalar
//      contracts carry zero dead code and zero solc warnings.
//    * Explicit NatSpec proof-boundary disclosure on every
//      generated file (D8a): Z3 unbounded Z vs EVM int256
//      checked revert Panic(0x11)/0x12, Euclidean vs truncating
//      negative division, and UTF-8 byte length for strings.
// ─────────────────────────────────────────────────────────────

