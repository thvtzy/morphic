fn escape_sol_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

// ── Function Renderer ─────────────────────────────────────

struct SolCtx<'a> {
    env: HashMap<String, SolValTy>,
    allowed_callees: &'a BTreeSet<String>,
    fn_ret: SolValTy,
    needed_append: &'a mut BTreeSet<&'static str>,
    needed_clone: &'a mut BTreeSet<&'static str>,
}

impl<'a> SolCtx<'a> {
    fn infer_expr_ty(&self, node: &IRNode) -> Option<SolValTy> {
        match node {
            IRNode::Var(name) => self.env.get(name).copied(),
            IRNode::Literal(lit) => match lit {
                IRLiteral::Int(_) => Some(SolValTy::Scalar("int256")),
                IRLiteral::Bool(_) => Some(SolValTy::Bool),
                IRLiteral::String(_) => Some(SolValTy::Str),
                IRLiteral::Unit => Some(SolValTy::Unit),
                _ => None,
            },
            IRNode::Call { function, .. } => match function.as_str() {
                "len" => Some(SolValTy::Scalar("int256")),
                name => crate::stdlib::prelude_specs()
                    .iter()
                    .find(|s| s.name == name)
                    .and_then(|s| sol_val_ty(&s.return_type, true).ok()),
            },
            IRNode::UnaryOp(IRUnaryOp::Len, _) => Some(SolValTy::Scalar("int256")),
            IRNode::UnaryOp(IRUnaryOp::Neg | IRUnaryOp::Abs, inner) => self.infer_expr_ty(inner),
            IRNode::UnaryOp(IRUnaryOp::Not, _) => Some(SolValTy::Bool),
            IRNode::UnaryOp(IRUnaryOp::Clone, inner) => self.infer_expr_ty(inner),
            IRNode::BinOp(op, lhs, _) => match op {
                IRBinOp::Eq
                | IRBinOp::Neq
                | IRBinOp::Lt
                | IRBinOp::Le
                | IRBinOp::Gt
                | IRBinOp::Ge
                | IRBinOp::And
                | IRBinOp::Or
                | IRBinOp::Xor => Some(SolValTy::Bool),
                IRBinOp::Concat => Some(SolValTy::Str),
                _ => self.infer_expr_ty(lhs).or(Some(SolValTy::Scalar("int256"))),
            },
            IRNode::Index(base, _) => match self.infer_expr_ty(base) {
                Some(SolValTy::List("bool")) => Some(SolValTy::Bool),
                Some(SolValTy::List(elem)) => Some(SolValTy::Scalar(elem)),
                _ => None,
            },
            IRNode::If { then_branch, .. } => self.infer_expr_ty(then_branch),
            IRNode::Typed { ty, .. } => sol_val_ty(ty, true).ok(),
            _ => None,
        }
    }

    fn infer_spec_expr_ty(&self, expr: &SpecExpr) -> Option<SolValTy> {
        match expr {
            SpecExpr::Var(name) => self.env.get(name).copied(),
            SpecExpr::IntLit(_) => Some(SolValTy::Scalar("int256")),
            SpecExpr::BoolLit(_) => Some(SolValTy::Bool),
            SpecExpr::StringLit(_) => Some(SolValTy::Str),
            SpecExpr::Length(_) => Some(SolValTy::Scalar("int256")),
            SpecExpr::Call(name, _) if name == "len" => Some(SolValTy::Scalar("int256")),
            SpecExpr::Index(base, _) => match self.infer_spec_expr_ty(base) {
                Some(SolValTy::List("bool")) => Some(SolValTy::Bool),
                Some(SolValTy::List(elem)) => Some(SolValTy::Scalar(elem)),
                _ => None,
            },
            SpecExpr::BinOp(op, lhs, _) => match op {
                SpecBinOp::Eq
                | SpecBinOp::Neq
                | SpecBinOp::Lt
                | SpecBinOp::Le
                | SpecBinOp::Gt
                | SpecBinOp::Ge
                | SpecBinOp::And
                | SpecBinOp::Or => Some(SolValTy::Bool),
                SpecBinOp::Concat => Some(SolValTy::Str),
                _ => self
                    .infer_spec_expr_ty(lhs)
                    .or(Some(SolValTy::Scalar("int256"))),
            },
            _ => None,
        }
    }
}

pub(crate) fn render_solidity_function(
    candidate: &CandidateImplementation,
    visibility: &str,
    extra_dev_doc: Option<&str>,
    allowed_callees: &BTreeSet<String>,
    needed_append: &mut BTreeSet<&'static str>,
    needed_clone: &mut BTreeSet<&'static str>,
) -> Result<String, CodegenError> {
    let spec = &candidate.spec;
    if !spec.generics.is_empty() {
        return Err(CodegenError::InvalidIR(format!(
            "target \"solidity\" does not support generic spec `{}`",
            spec.name
        )));
    }

    let mut env = HashMap::new();
    let mut param_strs = Vec::with_capacity(spec.params.len());
    for p in &spec.params {
        let vt = sol_val_ty(&p.ty, false)?;
        env.insert(p.name.clone(), vt);
        param_strs.push(format!("{} {}", sol_type_decl(vt), sol_ident(&p.name)));
    }
    let ret_ty = sol_val_ty(&spec.return_type, true)?;
    let ret_clause = match ret_ty {
        SolValTy::Unit => String::new(),
        other => format!(" returns ({})", sol_type_decl(other)),
    };

    let mut ctx = SolCtx {
        env,
        allowed_callees,
        fn_ret: ret_ty,
        needed_append,
        needed_clone,
    };

    let mut out = String::new();
    if let Some(doc) = &spec.doc {
        for line in doc.lines() {
            out.push_str(&format!("    /// @notice {line}\n"));
        }
    }
    if let Some(dev) = extra_dev_doc {
        out.push_str(&format!("    /// @dev {dev}\n"));
    }
    out.push_str(&format!(
        "    function {}({}) {} pure{} {{\n",
        sol_ident(&spec.name),
        param_strs.join(", "),
        visibility,
        ret_clause,
    ));

    // Preconditions: always-on runtime `require(...)`, hard-refusing
    // quantifiers and unrenderable expressions (D2a).
    for pre in &spec.preconditions {
        let cond = constraint_to_solidity(pre, &ctx)?;
        out.push_str(&format!(
            "        require({cond}, \"Precondition violated\");\n"
        ));
    }

    let body_code = ir_to_solidity_tail(&candidate.body, 2, &mut ctx)?;
    out.push_str(&body_code);
    out.push_str("    }\n");
    Ok(out)
}

// ── Precondition (`require:`) Renderer ────────────────────

fn constraint_to_solidity(cons: &Constraint, ctx: &SolCtx<'_>) -> Result<String, CodegenError> {
    match cons {
        Constraint::True => Ok("true".to_string()),
        Constraint::Expr(expr) => spec_expr_to_solidity(expr, ctx),
        Constraint::Predicate(name, args) => spec_call_to_solidity(name, args, ctx),
        Constraint::Not(inner) => Ok(format!("!({})", constraint_to_solidity(inner, ctx)?)),
        Constraint::Eq(a, b) => spec_eq_to_solidity(a, b, false, ctx),
        Constraint::Order(op, a, b) => {
            let sol_op = match op {
                OrderOp::LessThan => "<",
                OrderOp::LessThanOrEqual => "<=",
                OrderOp::GreaterThan => ">",
                OrderOp::GreaterThanOrEqual => ">=",
            };
            Ok(format!(
                "({} {} {})",
                spec_expr_to_solidity(a, ctx)?,
                sol_op,
                spec_expr_to_solidity(b, ctx)?
            ))
        }
        Constraint::And(parts) => {
            let mut rendered = Vec::with_capacity(parts.len());
            for p in parts {
                rendered.push(constraint_to_solidity(p, ctx)?);
            }
            Ok(format!("({})", rendered.join(" && ")))
        }
        Constraint::Or(parts) => {
            let mut rendered = Vec::with_capacity(parts.len());
            for p in parts {
                rendered.push(constraint_to_solidity(p, ctx)?);
            }
            Ok(format!("({})", rendered.join(" || ")))
        }
        Constraint::Implies(a, b) => Ok(format!(
            "(!({}) || ({}))",
            constraint_to_solidity(a, ctx)?,
            constraint_to_solidity(b, ctx)?
        )),
        Constraint::Forall { .. } | Constraint::Exists { .. } => Err(CodegenError::InvalidIR(
            "target \"solidity\" refuses quantified precondition (forall/exists cannot be \
             enforced at runtime; refusing silent require(true) fallback)"
                .to_string(),
        )),
    }
}

fn spec_eq_to_solidity(
    a: &SpecExpr,
    b: &SpecExpr,
    negated: bool,
    ctx: &SolCtx<'_>,
) -> Result<String, CodegenError> {
    let lhs = spec_expr_to_solidity(a, ctx)?;
    let rhs = spec_expr_to_solidity(b, ctx)?;
    let op = if negated { "!=" } else { "==" };
    if matches!(ctx.infer_spec_expr_ty(a), Some(SolValTy::Str))
        || matches!(ctx.infer_spec_expr_ty(b), Some(SolValTy::Str))
    {
        Ok(format!("(keccak256(bytes({lhs})) {op} keccak256(bytes({rhs})))"))
    } else {
        Ok(format!("({lhs} {op} {rhs})"))
    }
}

fn spec_len_to_solidity(inner: &SpecExpr, ctx: &SolCtx<'_>) -> Result<String, CodegenError> {
    let target = spec_expr_to_solidity(inner, ctx)?;
    match ctx.infer_spec_expr_ty(inner) {
        Some(SolValTy::Str) => Ok(format!("int256(bytes({target}).length)")),
        Some(SolValTy::List(_)) => Ok(format!("int256({target}.length)")),
        _ => Err(CodegenError::InvalidIR(format!(
            "target \"solidity\": cannot determine length kind for precondition expression `{target}`"
        ))),
    }
}

fn spec_call_to_solidity(
    name: &str,
    args: &[SpecExpr],
    ctx: &SolCtx<'_>,
) -> Result<String, CodegenError> {
    if name == "len" && args.len() == 1 {
        return spec_len_to_solidity(&args[0], ctx);
    }
    if ctx.allowed_callees.contains(name) {
        let mut rendered = Vec::with_capacity(args.len());
        for a in args {
            rendered.push(spec_expr_to_solidity(a, ctx)?);
        }
        return Ok(format!("{}({})", sol_ident(name), rendered.join(", ")));
    }
    Err(CodegenError::UnrenderableLibraryCall {
        target: "solidity".to_string(),
        name: name.to_string(),
    })
}

fn spec_expr_to_solidity(expr: &SpecExpr, ctx: &SolCtx<'_>) -> Result<String, CodegenError> {
    match expr {
        SpecExpr::Var(name) => Ok(sol_ident(name)),
        SpecExpr::IntLit(n) => Ok(n.to_string()),
        SpecExpr::BoolLit(b) => Ok(b.to_string()),
        SpecExpr::StringLit(s) => Ok(format!("\"{}\"", escape_sol_str(s))),
        SpecExpr::Length(inner) => spec_len_to_solidity(inner, ctx),
        SpecExpr::Index(base, idx) => {
            let b = spec_expr_to_solidity(base, ctx)?;
            let i = spec_expr_to_solidity(idx, ctx)?;
            Ok(format!("{b}[uint256({i})]"))
        }
        SpecExpr::Call(name, args) => spec_call_to_solidity(name, args, ctx),
        SpecExpr::MethodCall {
            receiver,
            name,
            args,
        } if name == "len" && args.is_empty() => spec_len_to_solidity(receiver, ctx),
        SpecExpr::UnaryOp(op, inner) => {
            let s = spec_expr_to_solidity(inner, ctx)?;
            match op {
                crate::spec::ast::UnaryOp::Neg => Ok(format!("(-({s}))")),
                crate::spec::ast::UnaryOp::Not => Ok(format!("(!({s}))")),
            }
        }
        SpecExpr::BinOp(op, lhs, rhs) => match op {
            SpecBinOp::Eq => spec_eq_to_solidity(lhs, rhs, false, ctx),
            SpecBinOp::Neq => spec_eq_to_solidity(lhs, rhs, true, ctx),
            SpecBinOp::Concat => Ok(format!(
                "string.concat({}, {})",
                spec_expr_to_solidity(lhs, ctx)?,
                spec_expr_to_solidity(rhs, ctx)?
            )),
            other => {
                let sym = match other {
                    SpecBinOp::Add => "+",
                    SpecBinOp::Sub => "-",
                    SpecBinOp::Mul => "*",
                    SpecBinOp::Div => "/",
                    SpecBinOp::Mod => "%",
                    SpecBinOp::And => "&&",
                    SpecBinOp::Or => "||",
                    SpecBinOp::Lt => "<",
                    SpecBinOp::Le => "<=",
                    SpecBinOp::Gt => ">",
                    SpecBinOp::Ge => ">=",
                    SpecBinOp::Eq | SpecBinOp::Neq | SpecBinOp::Concat => unreachable!(),
                };
                Ok(format!(
                    "({} {} {})",
                    spec_expr_to_solidity(lhs, ctx)?,
                    sym,
                    spec_expr_to_solidity(rhs, ctx)?
                ))
            }
        },
        other => Err(CodegenError::InvalidIR(format!(
            "target \"solidity\" refuses unsupported precondition expression `{other:?}`"
        ))),
    }
}

// ── IR → Solidity Translation ─────────────────────────────

fn ir_to_solidity_tail(
    node: &IRNode,
    indent: usize,
    ctx: &mut SolCtx<'_>,
) -> Result<String, CodegenError> {
    let pad = "    ".repeat(indent);
    match node {
        IRNode::Typed { node: inner, .. } => ir_to_solidity_tail(inner, indent, ctx),
        IRNode::Block(stmts) => {
            if stmts.is_empty() {
                return Ok(String::new());
            }
            let mut out = String::new();
            let last_idx = stmts.len() - 1;
            for (i, stmt) in stmts.iter().enumerate() {
                if i == last_idx {
                    out.push_str(&ir_to_solidity_tail(stmt, indent, ctx)?);
                } else {
                    out.push_str(&ir_to_solidity_stmt(stmt, indent, ctx)?);
                }
            }
            Ok(out)
        }
        IRNode::Return(_)
        | IRNode::Alloc { .. }
        | IRNode::Assign { .. }
        | IRNode::For { .. }
        | IRNode::While { .. } => ir_to_solidity_stmt(node, indent, ctx),
        IRNode::Let { name, value, body } => {
            let inferred = ctx
                .infer_expr_ty(value)
                .unwrap_or(SolValTy::Scalar("int256"));
            let val_code = ir_to_solidity_expr(value, Some(inferred), ctx)?;
            let prev = ctx.env.insert(name.clone(), inferred);
            let mut out = format!(
                "{pad}{} {} = {val_code};\n",
                sol_type_decl(inferred),
                sol_ident(name)
            );
            out.push_str(&ir_to_solidity_tail(body, indent, ctx)?);
            if let Some(old) = prev {
                ctx.env.insert(name.clone(), old);
            } else {
                ctx.env.remove(name);
            }
            Ok(out)
        }
        IRNode::If {
            condition,
            then_branch,
            else_branch,
        } => {
            let cond = ir_to_solidity_expr(condition, Some(SolValTy::Bool), ctx)?;
            let then_code = ir_to_solidity_tail(then_branch, indent + 1, ctx)?;
            let else_code = ir_to_solidity_tail(else_branch, indent + 1, ctx)?;
            Ok(format!(
                "{pad}if ({cond}) {{\n{then_code}{pad}}} else {{\n{else_code}{pad}}}\n"
            ))
        }
        other => {
            if ctx.fn_ret == SolValTy::Unit {
                ir_to_solidity_stmt(other, indent, ctx)
            } else {
                let expr = ir_to_solidity_expr(other, Some(ctx.fn_ret), ctx)?;
                Ok(format!("{pad}return {expr};\n"))
            }
        }
    }
}

fn ir_to_solidity_stmt(
    node: &IRNode,
    indent: usize,
    ctx: &mut SolCtx<'_>,
) -> Result<String, CodegenError> {
    let pad = "    ".repeat(indent);
    match node {
        IRNode::Typed { node: inner, .. } => ir_to_solidity_stmt(inner, indent, ctx),
        IRNode::Block(stmts) => {
            let mut out = String::new();
            for s in stmts {
                out.push_str(&ir_to_solidity_stmt(s, indent, ctx)?);
            }
            Ok(out)
        }
        IRNode::Return(expr) => {
            if ctx.fn_ret == SolValTy::Unit {
                Ok(format!("{pad}return;\n"))
            } else {
                let val = ir_to_solidity_expr(expr, Some(ctx.fn_ret), ctx)?;
                Ok(format!("{pad}return {val};\n"))
            }
        }
        IRNode::Alloc { name, ty, initial } => {
            let vt = sol_val_ty(ty, false)?;
            let ident = sol_ident(name);
            let out = match (vt, initial.as_ref()) {
                (
                    SolValTy::List(elem),
                    IRNode::Collection {
                        kind: CollectionKind::List,
                        elements,
                    },
                ) => {
                    let mut buf = format!(
                        "{pad}{elem}[] memory {ident} = new {elem}[]({});\n",
                        elements.len()
                    );
                    let elem_vt = if elem == "bool" {
                        SolValTy::Bool
                    } else {
                        SolValTy::Scalar(elem)
                    };
                    for (idx, el) in elements.iter().enumerate() {
                        let e = ir_to_solidity_expr(el, Some(elem_vt), ctx)?;
                        buf.push_str(&format!("{pad}{ident}[{idx}] = {e};\n"));
                    }
                    buf
                }
                _ => {
                    let init_code = ir_to_solidity_expr(initial, Some(vt), ctx)?;
                    format!("{pad}{} {ident} = {init_code};\n", sol_type_decl(vt))
                }
            };
            ctx.env.insert(name.clone(), vt);
            Ok(out)
        }
        IRNode::Assign { target, value } => {
            let target_code = match target.as_ref() {
                IRNode::Var(v) => sol_ident(v),
                IRNode::Index(base, idx) => {
                    let b = ir_to_solidity_expr(base, None, ctx)?;
                    let i = ir_to_solidity_expr(idx, Some(SolValTy::Scalar("int256")), ctx)?;
                    format!("{b}[uint256({i})]")
                }
                other => {
                    return Err(CodegenError::InvalidIR(format!(
                        "target \"solidity\" refuses unsupported assignment target `{other:?}`"
                    )));
                }
            };
            let expected = ctx.infer_expr_ty(target);
            let val_code = ir_to_solidity_expr(value, expected, ctx)?;
            Ok(format!("{pad}{target_code} = {val_code};\n"))
        }
        IRNode::BinOp(IRBinOp::Append, lhs, rhs) => {
            let var_name = match lhs.as_ref() {
                IRNode::Var(v) => v.as_str(),
                other => {
                    return Err(CodegenError::InvalidIR(format!(
                        "target \"solidity\" refuses Append on non-variable target `{other:?}`"
                    )));
                }
            };
            let elem = match ctx.env.get(var_name) {
                Some(SolValTy::List(e)) => *e,
                other => {
                    return Err(CodegenError::InvalidIR(format!(
                        "target \"solidity\" refuses Append on `{var_name}` of type `{other:?}`"
                    )));
                }
            };
            ctx.needed_append.insert(elem);
            let elem_vt = if elem == "bool" {
                SolValTy::Bool
            } else {
                SolValTy::Scalar(elem)
            };
            let item_code = ir_to_solidity_expr(rhs, Some(elem_vt), ctx)?;
            let ident = sol_ident(var_name);
            Ok(format!("{pad}{ident} = _morphic_append_{elem}({ident}, {item_code});\n"))
        }
        IRNode::If {
            condition,
            then_branch,
            else_branch,
        } => {
            let cond = ir_to_solidity_expr(condition, Some(SolValTy::Bool), ctx)?;
            let then_code = ir_to_solidity_stmt(then_branch, indent + 1, ctx)?;
            let else_is_empty = matches!(else_branch.as_ref(), IRNode::Block(v) if v.is_empty());
            if else_is_empty {
                Ok(format!("{pad}if ({cond}) {{\n{then_code}{pad}}}\n"))
            } else {
                let else_code = ir_to_solidity_stmt(else_branch, indent + 1, ctx)?;
                Ok(format!(
                    "{pad}if ({cond}) {{\n{then_code}{pad}}} else {{\n{else_code}{pad}}}\n"
                ))
            }
        }
        IRNode::For {
            var,
            start,
            end,
            body,
        } => {
            let s = ir_to_solidity_expr(start, Some(SolValTy::Scalar("int256")), ctx)?;
            let e = ir_to_solidity_expr(end, Some(SolValTy::Scalar("int256")), ctx)?;
            let v_ident = sol_ident(var);
            let prev = ctx.env.insert(var.clone(), SolValTy::Scalar("int256"));
            let body_code = ir_to_solidity_stmt(body, indent + 1, ctx)?;
            if let Some(old) = prev {
                ctx.env.insert(var.clone(), old);
            } else {
                ctx.env.remove(var);
            }
            Ok(format!(
                "{pad}for (int256 {v_ident} = {s}; {v_ident} < {e}; {v_ident}++) {{\n{body_code}{pad}}}\n"
            ))
        }
        IRNode::While { condition, body, .. } => {
            let cond = ir_to_solidity_expr(condition, Some(SolValTy::Bool), ctx)?;
            let body_code = ir_to_solidity_stmt(body, indent + 1, ctx)?;
            Ok(format!("{pad}while ({cond}) {{\n{body_code}{pad}}}\n"))
        }
        IRNode::Let { name, value, body } => {
            let inferred = ctx
                .infer_expr_ty(value)
                .unwrap_or(SolValTy::Scalar("int256"));
            let val_code = ir_to_solidity_expr(value, Some(inferred), ctx)?;
            let prev = ctx.env.insert(name.clone(), inferred);
            let mut out = format!(
                "{pad}{} {} = {val_code};\n",
                sol_type_decl(inferred),
                sol_ident(name)
            );
            out.push_str(&ir_to_solidity_stmt(body, indent, ctx)?);
            if let Some(old) = prev {
                ctx.env.insert(name.clone(), old);
            } else {
                ctx.env.remove(name);
            }
            Ok(out)
        }
        other => {
            let expr = ir_to_solidity_expr(other, None, ctx)?;
            Ok(format!("{pad}{expr};\n"))
        }
    }
}

fn ir_len_to_solidity(inner: &IRNode, ctx: &mut SolCtx<'_>) -> Result<String, CodegenError> {
    let target = ir_to_solidity_expr(inner, None, ctx)?;
    match ctx.infer_expr_ty(inner) {
        Some(SolValTy::Str) => Ok(format!("int256(bytes({target}).length)")),
        Some(SolValTy::List(_)) => Ok(format!("int256({target}.length)")),
        other => Err(CodegenError::InvalidIR(format!(
            "target \"solidity\": cannot render len(...) for operand `{target}` of type `{other:?}`"
        ))),
    }
}

fn ir_to_solidity_expr(
    node: &IRNode,
    expected: Option<SolValTy>,
    ctx: &mut SolCtx<'_>,
) -> Result<String, CodegenError> {
    match node {
        IRNode::Typed { node: inner, ty } => {
            let hint = sol_val_ty(ty, true).ok().or(expected);
            ir_to_solidity_expr(inner, hint, ctx)
        }
        IRNode::Var(name) => Ok(sol_ident(name)),
        IRNode::Literal(lit) => match lit {
            IRLiteral::Int(n) => Ok(n.to_string()),
            IRLiteral::Bool(b) => Ok(b.to_string()),
            IRLiteral::String(s) => Ok(format!("\"{}\"", escape_sol_str(s))),
            IRLiteral::Float(_) => Err(CodegenError::InvalidIR(
                "target \"solidity\" does not support Float literals".to_string(),
            )),
            IRLiteral::Char(_) => Err(CodegenError::InvalidIR(
                "target \"solidity\" does not support Char literals".to_string(),
            )),
            IRLiteral::Unit => Err(CodegenError::InvalidIR(
                "target \"solidity\" does not support Unit value expressions".to_string(),
            )),
        },
        IRNode::BinOp(op, lhs, rhs) => match op {
            IRBinOp::Eq | IRBinOp::Neq => {
                let l_str = matches!(ctx.infer_expr_ty(lhs), Some(SolValTy::Str));
                let r_str = matches!(ctx.infer_expr_ty(rhs), Some(SolValTy::Str));
                let l = ir_to_solidity_expr(lhs, None, ctx)?;
                let r = ir_to_solidity_expr(rhs, None, ctx)?;
                let sym = if matches!(op, IRBinOp::Eq) { "==" } else { "!=" };
                if l_str || r_str {
                    Ok(format!("(keccak256(bytes({l})) {sym} keccak256(bytes({r})))"))
                } else {
                    Ok(format!("({l} {sym} {r})"))
                }
            }
            IRBinOp::Xor => {
                let l = ir_to_solidity_expr(lhs, Some(SolValTy::Bool), ctx)?;
                let r = ir_to_solidity_expr(rhs, Some(SolValTy::Bool), ctx)?;
                Ok(format!("({l} != {r})"))
            }
            IRBinOp::Concat => {
                let l = ir_to_solidity_expr(lhs, Some(SolValTy::Str), ctx)?;
                let r = ir_to_solidity_expr(rhs, Some(SolValTy::Str), ctx)?;
                Ok(format!("string.concat({l}, {r})"))
            }
            IRBinOp::Append => {
                let elem = match ctx.infer_expr_ty(lhs).or(expected) {
                    Some(SolValTy::List(e)) => e,
                    other => {
                        return Err(CodegenError::InvalidIR(format!(
                            "target \"solidity\" refuses Append expression on `{other:?}`"
                        )));
                    }
                };
                ctx.needed_append.insert(elem);
                let l = ir_to_solidity_expr(lhs, Some(SolValTy::List(elem)), ctx)?;
                let elem_vt = if elem == "bool" {
                    SolValTy::Bool
                } else {
                    SolValTy::Scalar(elem)
                };
                let r = ir_to_solidity_expr(rhs, Some(elem_vt), ctx)?;
                Ok(format!("_morphic_append_{elem}({l}, {r})"))
            }
            IRBinOp::Shl | IRBinOp::Shr | IRBinOp::Merge => Err(CodegenError::InvalidIR(format!(
                "target \"solidity\" does not support binary operator `{op:?}`"
            ))),
            other => {
                let sym = match other {
                    IRBinOp::Add => "+",
                    IRBinOp::Sub => "-",
                    IRBinOp::Mul => "*",
                    IRBinOp::Div => "/",
                    IRBinOp::Mod => "%",
                    IRBinOp::And => "&&",
                    IRBinOp::Or => "||",
                    IRBinOp::Lt => "<",
                    IRBinOp::Le => "<=",
                    IRBinOp::Gt => ">",
                    IRBinOp::Ge => ">=",
                    _ => unreachable!(),
                };
                let l = ir_to_solidity_expr(lhs, None, ctx)?;
                let r = ir_to_solidity_expr(rhs, None, ctx)?;
                Ok(format!("({l} {sym} {r})"))
            }
        },
        IRNode::UnaryOp(op, inner) => match op {
            IRUnaryOp::Len => ir_len_to_solidity(inner, ctx),
            IRUnaryOp::Neg => Ok(format!("(-({}))", ir_to_solidity_expr(inner, expected, ctx)?)),
            IRUnaryOp::Not => Ok(format!("(!({}))", ir_to_solidity_expr(inner, Some(SolValTy::Bool), ctx)?)),
            IRUnaryOp::Abs => {
                let e = ir_to_solidity_expr(inner, expected, ctx)?;
                Ok(format!("(({e}) < 0 ? -({e}) : ({e}))"))
            }
            IRUnaryOp::Clone => {
                let inner_ty = ctx.infer_expr_ty(inner).or(expected);
                let e = ir_to_solidity_expr(inner, inner_ty, ctx)?;
                match inner_ty {
                    Some(SolValTy::List(elem)) => {
                        ctx.needed_clone.insert(elem);
                        Ok(format!("_morphic_clone_{elem}({e})"))
                    }
                    _ => Ok(e),
                }
            }
            other => Err(CodegenError::InvalidIR(format!(
                "target \"solidity\" does not support unary operator `{other:?}`"
            ))),
        },
        IRNode::If {
            condition,
            then_branch,
            else_branch,
        } => {
            let cond = ir_to_solidity_expr(condition, Some(SolValTy::Bool), ctx)?;
            let arm_ty = infer_concrete_ty(then_branch, ctx)
                .or_else(|| infer_concrete_ty(else_branch, ctx))
                .or(expected);
            let mut then_e = ir_to_solidity_expr(then_branch, arm_ty, ctx)?;
            let mut else_e = ir_to_solidity_expr(else_branch, arm_ty, ctx)?;
            // Solidity Error 1080: a non-negative integer literal (mobile type `uint8`)
            // in one ternary branch does not unify with a signed `int256` sibling unless
            // explicitly cast to the sibling's scalar type (caught by real solc 0.8.28
            // on `linear_vested` in Phase 170).
            if let Some(SolValTy::Scalar(s)) = arm_ty {
                if is_const_int_expr(then_branch) {
                    then_e = format!("{s}({then_e})");
                }
                if is_const_int_expr(else_branch) {
                    else_e = format!("{s}({else_e})");
                }
            }
            Ok(format!("({cond} ? {then_e} : {else_e})"))
        }
        IRNode::Index(base, idx) => {
            let b = ir_to_solidity_expr(base, None, ctx)?;
            let i = ir_to_solidity_expr(idx, Some(SolValTy::Scalar("int256")), ctx)?;
            Ok(format!("{b}[uint256({i})]"))
        }
        IRNode::Collection {
            kind: CollectionKind::List,
            elements,
        } if elements.is_empty() => {
            let elem = match expected {
                Some(SolValTy::List(e)) => e,
                _ => "int256",
            };
            Ok(format!("new {elem}[](0)"))
        }
        IRNode::Call { function, args } => {
            if function == "len" && args.len() == 1 {
                return ir_len_to_solidity(&args[0], ctx);
            }
            if function == "int_to_str" {
                return Err(CodegenError::UnrenderableLibraryCall {
                    target: "solidity".to_string(),
                    name: "int_to_str".to_string(),
                });
            }
            if ctx.allowed_callees.contains(function) {
                let mut rendered = Vec::with_capacity(args.len());
                for a in args {
                    rendered.push(ir_to_solidity_expr(a, None, ctx)?);
                }
                return Ok(format!("{}({})", sol_ident(function), rendered.join(", ")));
            }
            Err(CodegenError::UnrenderableLibraryCall {
                target: "solidity".to_string(),
                name: function.clone(),
            })
        }
        other => Err(CodegenError::InvalidIR(format!(
            "target \"solidity\" does not support IR node `{}`",
            ir_node_kind_name(other)
        ))),
    }
}

fn is_const_int_expr(node: &IRNode) -> bool {
    match node {
        IRNode::Literal(IRLiteral::Int(_)) => true,
        IRNode::Typed { node: inner, .. } => is_const_int_expr(inner),
        IRNode::UnaryOp(IRUnaryOp::Neg | IRUnaryOp::Abs, inner) => is_const_int_expr(inner),
        IRNode::BinOp(
            IRBinOp::Add | IRBinOp::Sub | IRBinOp::Mul | IRBinOp::Div | IRBinOp::Mod,
            l,
            r,
        ) => is_const_int_expr(l) && is_const_int_expr(r),
        _ => false,
    }
}

fn infer_concrete_ty(node: &IRNode, ctx: &SolCtx<'_>) -> Option<SolValTy> {
    if is_const_int_expr(node) {
        return None;
    }
    ctx.infer_expr_ty(node)
}

fn ir_node_kind_name(node: &IRNode) -> &'static str {
    match node {
        IRNode::Hole { .. } => "Hole",
        IRNode::Block(_) => "Block",
        IRNode::Let { .. } => "Let",
        IRNode::If { .. } => "If",
        IRNode::While { .. } => "While",
        IRNode::For { .. } => "For",
        IRNode::Match { .. } => "Match",
        IRNode::Call { .. } => "Call",
        IRNode::Return(_) => "Return",
        IRNode::Literal(_) => "Literal",
        IRNode::Var(_) => "Var",
        IRNode::BinOp(..) => "BinOp",
        IRNode::UnaryOp(..) => "UnaryOp",
        IRNode::Lambda { .. } => "Lambda",
        IRNode::Closure { .. } => "Closure",
        IRNode::Collection { .. } => "Collection",
        IRNode::Map { .. } => "Map",
        IRNode::Filter { .. } => "Filter",
        IRNode::Fold { .. } => "Fold",
        IRNode::Sort { .. } => "Sort",
        IRNode::Alloc { .. } => "Alloc",
        IRNode::Assign { .. } => "Assign",
        IRNode::Typed { .. } => "Typed",
        IRNode::Index(..) => "Index",
        IRNode::Loop { .. } => "Loop",
        IRNode::Break { .. } => "Break",
        IRNode::StructDef { .. } => "StructDef",
        IRNode::TryPropagate(_) => "TryPropagate",
        IRNode::FieldAccess { .. } => "FieldAccess",
        IRNode::RecordLit { .. } => "RecordLit",
    }
}

