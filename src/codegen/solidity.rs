pub(crate) fn render_append_helper(elem_ty: &str) -> String {
    format!(
        "    function _morphic_append_{elem_ty}({elem_ty}[] memory xs, {elem_ty} item) internal pure returns ({elem_ty}[] memory) {{\n\
         \x20       uint256 n = xs.length;\n\
         \x20       {elem_ty}[] memory out = new {elem_ty}[](n + 1);\n\
         \x20       for (uint256 i = 0; i < n; i++) {{\n\
         \x20           out[i] = xs[i];\n\
         \x20       }}\n\
         \x20       out[n] = item;\n\
         \x20       return out;\n\
         \x20   }}\n"
    )
}

